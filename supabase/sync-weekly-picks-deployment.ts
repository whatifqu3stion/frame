const generatedNotice = "// AUTO-GENERATED from supabase/functions. Do not edit this file directly.\n";

const files = [
  "_shared/edge-security.ts",
  "_shared/source-leases.ts",
  "_shared/source-resolution.ts",
  "_shared/source-ingestion.ts",
  "_shared/source-feed.ts",
  "_shared/weekly-picks-contract.ts",
  "_shared/weekly-picks.ts",
  "_shared/weekly-pick-preparation.ts",
  "_shared/weekly-pick-drafting.ts",
  "source-leases/index.ts",
  "resolve-source/index.ts",
  "sync-sources/index.ts",
  "source-feed/index.ts",
  "weekly-picks/index.ts",
  "draft-weekly-picks/index.ts",
] as const;

for (const relativePath of files) {
  const sourceUrl = new URL(`./functions/${relativePath}`, import.meta.url);
  const targetUrl = new URL(`../backend/functions/${relativePath}`, import.meta.url);
  await Deno.mkdir(new URL(".", targetUrl), { recursive: true });
  let source = await Deno.readTextFile(sourceUrl);
  if (relativePath.endsWith("/index.ts")) {
    source = source.replace(
      'from "@supabase/supabase-js"',
      'from "npm:@supabase/supabase-js@2"',
    );
  }
  await Deno.writeTextFile(targetUrl, `${generatedNotice}${source}`);
}
